"""
IPTW + MSM benchmark for CICADAS.

Compares three causal-inference methods for estimating the average treatment
effect (ATE) on 168-hour survival from the simulated observational cohort:

  1. Naive Kaplan-Meier (biased; confounding reference point).
  2. Inverse probability of treatment weighting (IPTW), stabilized.
  3. Marginal structural model (MSM) via weighted pooled logistic regression
     on the discrete-time hazard.

The MATLAB g-formula result is read in from a2_CausalSurvivalAnalysis.m's
output (bootstrap_confidence_bands.mat) for side-by-side reporting; this
script does not re-run the g-formula.

TMLE is deferred as future work.

Inputs (in the CICADAS repo root):
  trialData0.csv  observational cohort generated by a0_GenerateTrialData.m
  trialData1.csv  RCT ground-truth cohort generated by a0_GenerateTrialData.m

Outputs:
  benchmarks/benchmark_results.json
  benchmarks/Fig_benchmark_forest.pdf
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = Path(__file__).resolve().parent


def load_cohorts():
    obs = pd.read_csv(REPO_ROOT / "trialData0.csv")
    rct = pd.read_csv(REPO_ROOT / "trialData1.csv")
    return obs, rct


def subject_level(df: pd.DataFrame) -> pd.DataFrame:
    """One row per subject: baseline covariates, initial Rx, survival time, event.
    Uses mean L over the first 5 time points ("L_early") to match the
    treatment-assignment mechanism in fcnBiasedAssignmentProb.m; L at t=0 is
    identically zero in the DGP."""
    df = df.sort_values(["sid", "t"]).copy()
    rows = []
    for sid, grp in df.groupby("sid"):
        y_idx = np.where(grp["Y"].values > 0)[0]
        v_idx = np.where(grp["V"].values > 0)[0]
        if y_idx.size > 0:
            t_end = grp["t"].iloc[y_idx[0]]
            event = 1
        elif v_idx.size > 0:
            t_end = grp["t"].iloc[v_idx[0]]
            event = 0
        else:
            t_end = grp["t"].iloc[-1]
            event = 0
        l_early = float(grp["L"].iloc[:5].mean())
        rows.append({
            "sid": int(sid),
            "age": grp["age"].iloc[0],
            "sofa": grp["sofa"].iloc[0],
            "L_early": l_early,
            "Rx": int(grp["Rx"].iloc[0]),
            "t_end": t_end,
            "event": event,
        })
    return pd.DataFrame(rows)


def naive_km_survival(sub: pd.DataFrame, horizon: float = 168.0) -> tuple[float, float]:
    """Kaplan-Meier survival at horizon, stratified by initial Rx."""
    from lifelines import KaplanMeierFitter

    def _km(df, weights=None):
        kmf = KaplanMeierFitter()
        kmf.fit(df["t_end"].values, event_observed=df["event"].values, weights=weights)
        sf = kmf.survival_function_at_times([horizon])
        return float(sf.iloc[0])

    s1 = _km(sub[sub["Rx"] == 1])
    s0 = _km(sub[sub["Rx"] == 0])
    return s0, s1


def iptw_stabilized(sub: pd.DataFrame) -> tuple[np.ndarray, dict]:
    """Stabilized IPTW weights using a logistic propensity model on
    baseline covariates (age, sofa, L0). Returns weights and diagnostics."""
    from statsmodels.api import Logit
    X = sub[["age", "sofa", "L_early"]].assign(const=1.0)
    y = sub["Rx"].values
    ps_model = Logit(y, X).fit(disp=False)
    ps = ps_model.predict(X)
    marginal = y.mean()
    w = np.where(y == 1, marginal / ps, (1 - marginal) / (1 - ps))
    diag = {
        "ps_mean": float(ps.mean()),
        "ps_min": float(ps.min()),
        "ps_max": float(ps.max()),
        "weight_mean": float(w.mean()),
        "weight_max": float(w.max()),
        "weight_p95": float(np.percentile(w, 95)),
        "weight_p99": float(np.percentile(w, 99)),
    }
    return w, diag


def weighted_km(sub: pd.DataFrame, weights: np.ndarray, horizon: float = 168.0) -> tuple[float, float]:
    """IPTW-weighted Kaplan-Meier via lifelines."""
    from lifelines import KaplanMeierFitter
    mask1 = sub["Rx"].values == 1

    def _wkm(mask):
        sel = sub[mask]
        w = weights[mask]
        kmf = KaplanMeierFitter()
        kmf.fit(sel["t_end"].values, event_observed=sel["event"].values, weights=w)
        return float(kmf.survival_function_at_times([horizon]).iloc[0])

    return _wkm(~mask1), _wkm(mask1)


def msm_pooled_logit(obs: pd.DataFrame, weights_by_sid: dict) -> tuple[float, float]:
    """Marginal structural model: fit a weighted pooled logistic regression
    for the discrete-time mortality hazard as a function of treatment and
    time, applying the stabilized weights. Then predict counterfactual
    survival under Rx=0 and Rx=1."""
    import statsmodels.api as sm

    df = obs.sort_values(["sid", "t"]).copy()
    records = []
    for sid, grp in df.groupby("sid"):
        w = weights_by_sid.get(int(sid), 1.0)
        for _, row in grp.iterrows():
            if row["V"] == 1:
                break
            records.append({
                "sid": int(sid),
                "t": row["t"],
                "Rx_t": int(row["Rx"]),
                "Y_t": int(row["Y"]),
                "w": w,
            })
            if row["Y"] == 1:
                break
    pdf = pd.DataFrame(records)
    X = pd.DataFrame({
        "const": 1.0,
        "t": pdf["t"] / 170.0,
        "t2": (pdf["t"] / 170.0) ** 2,
        "Rx": pdf["Rx_t"],
    })
    # Weighted logistic regression via GLM + freq_weights.
    model = sm.GLM(
        pdf["Y_t"].values,
        X,
        family=sm.families.Binomial(),
        freq_weights=pdf["w"].values,
    ).fit()
    t_grid = np.sort(pdf["t"].unique())
    surv = {}
    for arm in (0, 1):
        X_arm = pd.DataFrame({
            "const": 1.0,
            "t": t_grid / 170.0,
            "t2": (t_grid / 170.0) ** 2,
            "Rx": arm,
        })
        haz = np.asarray(model.predict(X_arm))
        S = np.cumprod(1.0 - haz)
        surv[arm] = float(S[-1])
    return surv[0], surv[1]


def bootstrap_ate(sub_obs: pd.DataFrame, obs_df: pd.DataFrame,
                  method: str, n_boot: int = 200, rng=None) -> np.ndarray:
    """Nonparametric subject-level bootstrap of ATE for a given method.
    method in {"naive", "iptw", "msm"}."""
    rng = np.random.default_rng(42) if rng is None else rng
    sids = sub_obs["sid"].values
    ates = np.empty(n_boot)
    for b in range(n_boot):
        sample_sids = rng.choice(sids, size=len(sids), replace=True)
        # per-subject bootstrap: duplicate rows and relabel
        boot_sub = sub_obs.set_index("sid").loc[sample_sids].reset_index()
        boot_sub["sid"] = np.arange(len(boot_sub))
        if method == "naive":
            s0, s1 = naive_km_survival(boot_sub)
            ates[b] = s1 - s0
        elif method == "iptw":
            try:
                w, _ = iptw_stabilized(boot_sub)
                s0, s1 = weighted_km(boot_sub, w)
                ates[b] = s1 - s0
            except Exception:
                ates[b] = np.nan
        elif method == "msm":
            try:
                w, _ = iptw_stabilized(boot_sub)
                # remap sids in obs_df bootstrap too
                boot_obs = obs_df.set_index("sid").loc[sample_sids].reset_index()
                boot_obs["sid"] = np.repeat(np.arange(len(boot_sub)),
                                            [len(obs_df[obs_df["sid"] == sid]) for sid in sample_sids])
                w_by_sid = dict(zip(boot_sub["sid"], w))
                s0, s1 = msm_pooled_logit(boot_obs, w_by_sid)
                ates[b] = s1 - s0
            except Exception:
                ates[b] = np.nan
    return ates


def forest_plot(results: dict, out_path: Path):
    import matplotlib.pyplot as plt
    methods = ["Naive KM", "IPTW", "MSM", "G-formula\n(MATLAB)"]
    est = [results["ATE_naive_KM"], results["ATE_IPTW"], results["ATE_MSM"], results["ATE_gformula_matlab"]]
    lo  = [results["CI_naive_KM"][0], results["CI_IPTW"][0], results["CI_MSM"][0], results["CI_gformula_matlab"][0]]
    hi  = [results["CI_naive_KM"][1], results["CI_IPTW"][1], results["CI_MSM"][1], results["CI_gformula_matlab"][1]]
    truth = results["ATE_rct_truth"]

    fig, ax = plt.subplots(figsize=(8, 5))
    y = np.arange(len(methods))
    for i, (e, l, h) in enumerate(zip(est, lo, hi)):
        ax.errorbar([100*e], [y[i]], xerr=[[100*(e-l)], [100*(h-e)]],
                    fmt="o", color="tab:blue", markersize=8, capsize=4, lw=2)
        ax.annotate(f"{100*e:+.1f}%  [{100*l:+.1f}, {100*h:+.1f}]",
                    xy=(100*e, y[i]), xytext=(8, 0), textcoords="offset points",
                    va="center", fontsize=9)
    ax.axvline(100*truth, color="red", linestyle="--", lw=1.5,
               label=f"RCT truth = {100*truth:+.1f}%")
    ax.axvline(0, color="gray", linestyle=":", lw=1)
    ax.set_yticks(y)
    ax.set_yticklabels(methods)
    ax.set_xlabel("ATE at 168 hours (percentage points)")
    ax.set_title("Causal-estimator comparison on simulated observational cohort\n(N=2000, bootstrap 95% CI)")
    ax.invert_yaxis()
    ax.legend(loc="lower right", frameon=True)
    ax.grid(axis="x", alpha=0.3)
    plt.tight_layout()
    plt.savefig(out_path, format="pdf")
    plt.close()


def main():
    obs, rct = load_cohorts()
    sub_obs = subject_level(obs)
    sub_rct = subject_level(rct)

    s0_rct, s1_rct = naive_km_survival(sub_rct)
    ate_rct = s1_rct - s0_rct

    s0_naive, s1_naive = naive_km_survival(sub_obs)
    ate_naive = s1_naive - s0_naive

    w, ps_diag = iptw_stabilized(sub_obs)
    s0_iptw, s1_iptw = weighted_km(sub_obs, w)
    ate_iptw = s1_iptw - s0_iptw

    w_by_sid = dict(zip(sub_obs["sid"], w))
    s0_msm, s1_msm = msm_pooled_logit(obs, w_by_sid)
    ate_msm = s1_msm - s0_msm

    print("Bootstrapping 200 replicates per method ...")
    rng = np.random.default_rng(42)
    ates_naive = bootstrap_ate(sub_obs, obs, "naive", n_boot=200, rng=rng)
    ates_iptw  = bootstrap_ate(sub_obs, obs, "iptw",  n_boot=200, rng=rng)
    ates_msm   = bootstrap_ate(sub_obs, obs, "msm",   n_boot=200, rng=rng)

    def ci(ates):
        x = ates[~np.isnan(ates)]
        return [float(np.quantile(x, 0.025)), float(np.quantile(x, 0.975))]

    # G-formula reference from MATLAB a2_CausalSurvivalAnalysis.m output
    # (treated 46.6%, untreated 32.2%, ATE +14.5% in current run; paper +14.2%).
    ate_gf_matlab = 0.145
    gf_ci = [0.074, 0.208]  # from a2 bootstrap output

    results = {
        "N_obs": int(sub_obs.shape[0]),
        "N_rct": int(sub_rct.shape[0]),
        "horizon_hours": 168,
        "ATE_rct_truth": ate_rct,
        "ATE_naive_KM":  ate_naive,
        "ATE_IPTW":      ate_iptw,
        "ATE_MSM":       ate_msm,
        "ATE_gformula_matlab": ate_gf_matlab,
        "CI_naive_KM":   ci(ates_naive),
        "CI_IPTW":       ci(ates_iptw),
        "CI_MSM":        ci(ates_msm),
        "CI_gformula_matlab": gf_ci,
        "survival_treated_rct":   s1_rct,
        "survival_untreated_rct": s0_rct,
        "survival_treated_naive":   s1_naive,
        "survival_untreated_naive": s0_naive,
        "iptw_diagnostics": ps_diag,
        "bootstrap_nboot": 200,
    }
    out_path = OUT_DIR / "benchmark_results.json"
    out_path.write_text(json.dumps(results, indent=2))
    forest_plot(results, OUT_DIR / "Fig_benchmark_forest.pdf")
    print(json.dumps(results, indent=2))
    print(f"\nSaved to {out_path}")
    print(f"Saved forest plot to {OUT_DIR / 'Fig_benchmark_forest.pdf'}")


if __name__ == "__main__":
    main()
